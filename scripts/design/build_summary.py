"""Generate read-only home counts from the existing review projections.
No selection, grading, storage writes or notifications are run by this adapter.
"""
import json, re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from scripts.history.embed import APPS, questions
source=(ROOT/'scripts/practice/adaptive.js').read_text()
def function(name):
 start=source.index('function '+name+'(')
 line=source[start:source.index('\n',start)]
 if line.endswith('}'):return line
 end=source.find('\n}',start)+2
 return source[start:end]
weak=function('weaknesses')
# Confusion is an explanation-only field, never used by counts. Do not run grading.
weak=re.sub(r'const confusion=QUESTIONS\.filter.*?\.some\(.*?;', 'const confusion=false;',weak,flags=re.S)
catalog={}
for file in APPS:
 text=(ROOT/file).read_text()
 key=re.search(r"LEGACY_KEY='([^']+)'",text)[1]
 qs=questions(text)
 catalog[file]={'key':'yuika-prototype-v1:'+key,'science':file=='yuika-review-v2.html','questions':[{k:q[k] for k in ('id','unit','course','level','type') if k in q}|{'yomi':q['type']=='text' and bool(q.get('readings')) and bool(re.search(r'[\u3400-\u9fff]',q.get('answer','')))} for q in qs]}
body='''/* Generated by scripts/design/build_summary.py. Do not hand-edit. */
(()=>{
'use strict';
const catalog=CATALOG;
window.YuikaDesign.summary=function(file){
 try{
 const meta=catalog[file];if(!meta)throw Error('unknown unit');
 const store=window.YuikaParent.storage,raw=JSON.parse(store.getItem(meta.key)||'{"events":[]}');
 if(!Array.isArray(raw.events))throw Error('invalid records');
 const events=raw.events.map(e=>({...e,at:e.at||e.answeredAt,hint:e.hint??e.hintUsed,variant:e.variant||'normal'}));
 const QUESTIONS=meta.questions,Q=new Map(QUESTIONS.map(q=>[q.id,q]));
 if(!meta.science)for(const q of QUESTIONS)Q.set(q.id+'-review-v1',{...q,originId:q.id});
 const now=Date.now(),today=new Date(now+9*3600000).toISOString().slice(0,10);
 const data={events},blocked=false,dirty=false;
 const order=es=>[...es].sort((a,b)=>a.at.localeCompare(b.at)||a.id.localeCompare(b.id));
 const japanDay=iso=>new Date(Date.parse(iso)+9*3600000).toISOString().slice(0,10);
 const REVIEW_INTERVAL_DAYS=[1,3,7];
 const addJapanDays=(d,n)=>new Date(Date.parse(d+'T00:00:00Z')+n*86400000).toISOString().slice(0,10);
FUNCTIONS
 const prefs={count:5,course:'all',unit:'all',variant:'normal'};
 const saved=JSON.parse(store.getItem(meta.key+'-preferences-v1')||'null');
 if(saved){if((meta.science?[5,10]:[5,10,15]).includes(saved.count))prefs.count=saved.count;if(QUESTIONS.some(q=>q.unit===saved.unit))prefs.unit=saved.unit;if(!meta.science){if(QUESTIONS.some(q=>q.course===saved.course))prefs.course=saved.course;if(['normal','kanji','yomi'].includes(saved.variant))prefs.variant=saved.variant;}}
 const matches=q=>(prefs.unit==='all'||q.unit===prefs.unit)&&(prefs.course==='all'||q.course===prefs.course)&&(prefs.variant==='normal'||(prefs.variant==='kanji'?q.type==='text':q.yomi));
 const latest=new Map();for(const e of order(events))if(Q.has(e.questionId)&&e.variant==='normal')latest.set(Q.get(e.questionId).originId||e.questionId,e);
 const unavailable=practiceUnavailable(events,now);
 const states=unavailable?[]:retention(events,now);
 const due=states.filter(s=>s.status==='waiting'&&s.due<=today&&s.variant===prefs.variant&&matches(Q.get(s.originId)));
 const weak=unavailable?[]:practiceWeaknesses(events,now).filter(s=>s.variant===prefs.variant&&matches(Q.get(s.originId))).slice(0,10);
 const ids=new Set(due.map(s=>s.originId));const dueCount=Math.min(prefs.count,ids.size);
 let weakCount=0;for(const r of weak)if(!ids.has(r.originId)){ids.add(r.originId);weakCount++;}
 weakCount=Math.min(prefs.count-dueCount,weakCount);
 const total=Math.min(prefs.count,QUESTIONS.filter(matches).length);
 return {correct:[...latest.values()].filter(e=>e.correct).length,total:QUESTIONS.length,due:due.length,dueCount,weakCount,normalCount:Math.max(0,total-dueCount-weakCount),unavailable};
 }catch{return null;}
};
})();
'''.replace('CATALOG',json.dumps(catalog,ensure_ascii=False,separators=(',',':'))).replace('FUNCTIONS','\n'.join([weak,function('practiceClockIssue'),function('practiceUnavailable'),function('retention'),function('practiceWeaknesses')]))
(ROOT/'assets/progress.js').write_text(body)
