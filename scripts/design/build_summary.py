"""Generate read-only home counts from the existing review projections.
Validation uses the unit loaders (including historical grade consistency checks).
No selection, record rewriting, storage writes or notifications run here.
"""
import ast, json, re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from scripts.history.embed import APPS, questions
source=(ROOT/'scripts/practice/adaptive.js').read_text()
def function(name, source=source):
 start=source.index('function '+name+'(')
 line=source[start:source.index('\n',start)]
 if line.endswith('}'):return line
 end=source.find('\n}',start)+2
 return source[start:end]
weak=function('weaknesses')
# Confusion is an explanation-only field, never used by counts. Do not run grading.
weak=re.sub(r'const confusion=QUESTIONS\.filter.*?\.some\(.*?;', 'const confusion=false;',weak,flags=re.S)
def declaration(name, text):
 # These audited helpers are one-line declarations in the standalone loaders.
 return re.search(r'^const '+name+r'=.*$',text,re.M)[0]

def validator(text, science):
 # Embed the exact pure loading boundary, not a second approximation of it.
 # No DOM, storage, selection, notification or save functions are included.
 names=(['MODES','emptyState','localDay','sorted','grade','legacyIdentity'] if science else
        ['MODES','empty','order','day','normalize'])
 if not science and 'const VARIANTS=' in text:
  names += ['VARIANTS','canYomi','fits','variantOf','promptOf','expectedOf']
 constants=[declaration(name,text) for name in names]
 constants += ["const VERSION="+json.dumps(re.search(r"const VERSION='([^']+)'",text)[1])+";"]
 unit=re.search(r"UNIT_ID='([^']+)'",text)
 if unit: constants.append('const UNIT_ID='+json.dumps(unit[1])+';')
 constants.append(declaration('QUESTION_REVISIONS',text))
 if science: constants.append('const byId=true;')
 constants.append("MODES.adaptive='弱点に合わせた追加練習';MODES.daily='今日の5問';")
 names=(['numeric','requireThat','validDate','legacyData','validateEvent','validateState'] if science else
        ['grade','check','validDate','validateEvent','validate'])
 functions=[function(name,text) for name in names]+[function('historicalQuestion',text)]
 load='validateState' if science else 'validate'
 empty='emptyState' if science else 'empty'
 return '(()=>{\n'+'\n'.join(constants+functions)+f'\nreturn raw=>raw===null?{empty}():{load}(JSON.parse(raw));\n'+'})()'

catalog={}
validators={}
for file in APPS:
 text=(ROOT/file).read_text()
 key=re.search(r"LEGACY_KEY='([^']+)'",text)[1]
 qs=questions(text)
 validators[file]=validator(text,file=='yuika-review-v2.html')
 if file=='yuika-review-v2.html': variants=['normal']
 elif 'const VARIANTS=' in text: variants=re.findall(r'(\w+):',declaration('VARIANTS',text))
 else: variants=ast.literal_eval(re.search(r'(\[[^\]\n]+\])\.includes\(p.variant\)',text)[1])
 catalog[file]={'key':'yuika-prototype-v1:'+key,'science':file=='yuika-review-v2.html','variants':variants,'questions':[{k:q[k] for k in ('id','unit','course','level','type') if k in q}|{'yomi':q['type']=='text' and bool(q.get('readings')) and bool(re.search(r'[\u3400-\u9fff]',q.get('answer','')))} for q in qs]}
